// Regenerates lib/legal-powerups-content.mjs (the /terms and /privacy text) from the SOT Power-ups legal markdown.
// Usage: node scripts/sync-powerups-legal.mjs [path to SOT/07-publishing/Website]
// The legal text is copied verbatim; only frontmatter is dropped and [[wikilinks]] become site links.
import { readFileSync, writeFileSync } from 'node:fs';
import { join, resolve } from 'node:path';

export const SOT_FILES = {
  terms: 'Salmon Terms And Conditions Powerups 1.4',
  privacy: 'Salmon Privacy Policy Powerups 1.4',
};
const LOCALES = ['en', 'es', 'pt'];

export function powerupsPath(locale, kind) {
  return `${locale === 'en' ? '' : `/${locale}`}/${kind}`;
}

const wikiTargets = Object.fromEntries(
  LOCALES.flatMap((locale) =>
    Object.entries(SOT_FILES).map(([kind, name]) => [`${name} ${locale.toUpperCase()}`, powerupsPath(locale, kind)])
  )
);

export function convertSotMarkdown(source) {
  const match = source.match(/^---\n([\s\S]*?)\n---\n/);
  if (!match) throw new Error('missing frontmatter');
  const title = match[1].match(/^title: (.+)$/m)?.[1].trim();
  if (!title) throw new Error('missing title');
  const markdown = source.slice(match[0].length).trim().replace(/\[\[([^\]|]+)\|([^\]]+)\]\]/g, (_, target, label) => {
    const href = wikiTargets[target];
    if (!href) throw new Error(`unknown wikilink target: ${target}`);
    return `[${label}](${href})`;
  });
  if (markdown.includes('[[')) throw new Error('unconverted wikilink');
  return { title, markdown };
}

export function readSot(dir, locale, kind) {
  return readFileSync(join(dir, `${SOT_FILES[kind]} ${locale.toUpperCase()}.md`), 'utf8');
}

if (import.meta.url === `file://${process.argv[1]}`) {
  const dir = resolve(process.argv[2] ?? '../SOT/07-publishing/Website');
  const content = Object.fromEntries(
    LOCALES.map((locale) => [
      locale,
      Object.fromEntries(Object.keys(SOT_FILES).map((kind) => [kind, convertSotMarkdown(readSot(dir, locale, kind))])),
    ])
  );
  writeFileSync(
    new URL('../lib/legal-powerups-content.mjs', import.meta.url),
    `// Generated by scripts/sync-powerups-legal.mjs from the SOT. Do not edit by hand.\nexport const powerupsLegalContent = ${JSON.stringify(content, null, 2)};\n`
  );
  console.log('wrote lib/legal-powerups-content.mjs');
}
